// Tulis perulangan FOR dan WHILE di sini


for (i = 0; i <= 20 ; i ++) {
    console.log (i + " - I love Coding");
}

for (j = 20; j >= 0; j --) {
    console.log (j + " - I will become fullstack developer");
}

let k = 2;

while (k <= 20) {
    console.log(k + " - I Love Coding  ");
    k += 2;
}

let l = 18;

while (l >= 2) {
    console.log(l + " - I Will become fullstack");
    l -= 2;
}